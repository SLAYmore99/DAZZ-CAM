#!/usr/bin/env python3
"""Generates web/data.js from the Android sources so the iPhone web app always matches:
shaders from gl/Shaders.kt and the camera roster from model/Cameras.kt."""
import json, os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(ROOT, 'app/src/main/java/com/funcam/app')

sh = open(os.path.join(SRC, 'gl/Shaders.kt')).read()
shaders = {k: re.search(r'const val ' + k + r' = """(.*?)"""', sh, re.S).group(1) for k in ['VERTEX', 'INPUT', 'COPY', 'FILM']}
# Web input is a regular 2D texture (video element), already upright.
shaders['INPUT'] = shaders['INPUT'].replace('#extension GL_OES_EGL_image_external_essl3 : require\n', '') \
    .replace('samplerExternalOES', 'sampler2D')

cams = open(os.path.join(SRC, 'model/Cameras.kt')).read()
named = dict(re.findall(r'private val (\w+) = Ratio\((\d+), (\d+)\)', cams) and
             [(n, (int(a), int(b))) for n, a, b in re.findall(r'private val (\w+) = Ratio\((\d+), (\d+)\)', cams)])

def ratios(txt):
    out = []
    for tok in re.findall(r'Ratio\(\d+, \d+\)|\b\w+\b', txt):
        m = re.match(r'Ratio\((\d+), (\d+)\)', tok)
        if m: out.append([int(m.group(1)), int(m.group(2))])
        elif tok in named: out.append(list(named[tok]))
    return out

recipes = []
pat = re.compile(r'Recipe\(\s*"(\w+)", "([^"]+)", Category\.(\w+), Body\.(\w+), 0x(\w+), 0x(\w+),\s*"((?:[^"\\]|\\.)*)",\s*Look\((.*?)\),\s*\n(.*?)\n        \),', re.S)
for m in pat.finditer(cams):
    cid, name, cat, body, c1, c2, desc, look, rest = m.groups()
    L = {}
    for k, a, b, c in re.findall(r'(\w+) = V3\(([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f\)', look):
        L[k] = [float(a), float(b), float(c)]
    for k, v in re.findall(r'(\w+) = (-?[\d.]+)f\b', look):
        L.setdefault(k, float(v))
    get = lambda pat_, d=None: (re.search(pat_, rest).group(1) if re.search(pat_, rest) else d)
    rl = None
    i = rest.find('ratios = listOf(')
    if i >= 0:
        j = i + len('ratios = listOf('); depth = 1; k = j
        while depth:
            depth += {'(': 1, ')': -1}.get(rest[k], 0); k += 1
        rl = re.match(r'(.*)', rest[j:k - 1], re.S)
    recipes.append(dict(
        id=cid, name=name, category=cat, body=body, bodyColor='#' + c1[2:], accentColor='#' + c2[2:],
        description=desc.replace('\\"', '"'), look=L,
        ratios=ratios(rl.group(1)) if rl else [[3, 4]],
        border=get(r'border = Border\.(\w+)', 'NONE'), capture=get(r'capture = CaptureMode\.(\w+)', 'SINGLE'),
        stamp=get(r'stamp = StampStyle\.(\w+)', 'FILM_ORANGE'), isVideo=get(r'isVideo = (true)', 'false') == 'true',
        videoFps=int(get(r'videoFps = (\d+)', '30')), manual=get(r'manual = (true)', 'false') == 'true',
        canImport=get(r'canImport = (false)', 'true') == 'true',
    ))

shutters = [eval(x.replace('f', '')) for x in re.findall(r'(1 / \d+f|1f)', re.search(r'SHUTTER_SPEEDS = listOf\((.*?)\)\n', cams, re.S).group(1))]
fps = [int(x) for x in re.search(r'FPS_VALUES = listOf\((.*?)\)', cams).group(1).split(',')]

with open(os.path.join(ROOT, 'web/data.js'), 'w') as f:
    f.write('// Generated by tools/gen_web_data.py from the Android sources. Do not edit.\n')
    f.write('export const SHADERS = ' + json.dumps(shaders) + ';\n')
    f.write('export const CAMERAS = ' + json.dumps(recipes, indent=1) + ';\n')
    f.write('export const SHUTTER_SPEEDS = ' + json.dumps(shutters) + ';\n')
    f.write('export const FPS_VALUES = ' + json.dumps(fps) + ';\n')
print(f'{len(recipes)} cameras written to web/data.js')
